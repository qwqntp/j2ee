SET client_encoding = 'UTF8';

-- ============================================================
-- PART 1: CORE TABLES
-- ============================================================

CREATE TABLE account_roles (
    account_role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL
);

CREATE TABLE accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,                 -- bcrypt hash
    account_email VARCHAR(255) NULL,                -- populated by signup/OAuth
    email_verified SMALLINT NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL DEFAULT 1,
    account_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    account_updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    role_id BIGINT NOT NULL,
    CONSTRAINT fk_account_role FOREIGN KEY (role_id) REFERENCES account_roles(account_role_id),
    CONSTRAINT ck_account_email_verified CHECK (email_verified IN (0, 1)),
    CONSTRAINT ck_account_status CHECK (status IN (0, 1))
);

-- Keep account_updated_at synchronized with PostgreSQL.
CREATE OR REPLACE FUNCTION set_account_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.account_updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_accounts_updated_at
    BEFORE UPDATE ON accounts
    FOR EACH ROW EXECUTE FUNCTION set_account_updated_at();

CREATE TABLE accommodations (
    accommodation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accommodation_name VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    rating DECIMAL(3,1) NULL,
    price_per_night DECIMAL(12,2) NULL,
    accommodation_type VARCHAR(20) NULL,
    CONSTRAINT ck_accommodation_rating CHECK (rating IS NULL OR (rating >= 0 AND rating <= 5)),
    CONSTRAINT ck_accommodation_price CHECK (price_per_night IS NULL OR price_per_night >= 0),
    CONSTRAINT ck_accommodation_type CHECK (
        accommodation_type IS NULL OR accommodation_type IN ('HOTEL', 'RESORT', 'HOMESTAY')
    )
);

CREATE TABLE travel_vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(255) NOT NULL,
    capacity INT NOT NULL,
    rental_price_per_day DECIMAL(12,2) NOT NULL,
    CONSTRAINT ck_vehicle_capacity CHECK (capacity > 0),
    CONSTRAINT ck_vehicle_rental_price CHECK (rental_price_per_day >= 0)
);

CREATE TABLE tour_guides (
    tour_guide_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_guide_name VARCHAR(255) NOT NULL,
    tour_guide_email VARCHAR(255) NULL,
    tour_guide_phone VARCHAR(20) NULL,
    tour_guide_experience_years INT NOT NULL DEFAULT 0,
    CONSTRAINT ck_guide_experience CHECK (tour_guide_experience_years >= 0)
);

CREATE TABLE tourist_destinations (
    destination_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_name VARCHAR(255) NOT NULL,
    location VARCHAR(255) NULL,
    description TEXT NULL,
    entry_fee DECIMAL(12,2) NULL,
    CONSTRAINT ck_destination_entry_fee CHECK (entry_fee IS NULL OR entry_fee >= 0)
);

CREATE TABLE promotions (
    promotion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_name VARCHAR(255) NOT NULL,
    discount_percentage DECIMAL(5,2) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    description TEXT NULL,
    CONSTRAINT ck_promotion_discount CHECK (discount_percentage >= 0 AND discount_percentage <= 100),
    CONSTRAINT ck_promotion_dates CHECK (end_date >= start_date)
);

-- A tour is the product definition. Dates, capacity, and price live on departures.
CREATE TABLE tours (
    tour_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_name VARCHAR(255) NOT NULL,
    tour_description TEXT NULL,
    tour_duration_days INT NULL,
    tour_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    accommodation_id BIGINT NULL,
    tour_guide_id BIGINT NULL,
    promotion_id BIGINT NULL,
    CONSTRAINT fk_tour_accommodation FOREIGN KEY (accommodation_id) REFERENCES accommodations(accommodation_id),
    CONSTRAINT fk_tour_guide FOREIGN KEY (tour_guide_id) REFERENCES tour_guides(tour_guide_id),
    CONSTRAINT fk_tour_promotion FOREIGN KEY (promotion_id) REFERENCES promotions(promotion_id),
    CONSTRAINT ck_tour_status CHECK (tour_status IN ('DRAFT', 'OPEN', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_tour_duration CHECK (tour_duration_days IS NULL OR tour_duration_days > 0)
);

CREATE INDEX idx_tour_status ON tours (tour_status);

CREATE TABLE tour_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url VARCHAR(512) NOT NULL,
    tour_id BIGINT NOT NULL,
    CONSTRAINT fk_image_tour FOREIGN KEY (tour_id) REFERENCES tours(tour_id)
);

CREATE INDEX idx_image_tour ON tour_images (tour_id);

CREATE TABLE tour_destinations (
    tour_id BIGINT NOT NULL,
    destination_id BIGINT NOT NULL,
    PRIMARY KEY (tour_id, destination_id),
    CONSTRAINT fk_td_tour FOREIGN KEY (tour_id) REFERENCES tours(tour_id),
    CONSTRAINT fk_td_destination FOREIGN KEY (destination_id) REFERENCES tourist_destinations(destination_id)
);

CREATE TABLE tour_vehicles (
    tour_id BIGINT NOT NULL,
    vehicle_id BIGINT NOT NULL,
    PRIMARY KEY (tour_id, vehicle_id),
    CONSTRAINT fk_tv_tour FOREIGN KEY (tour_id) REFERENCES tours(tour_id),
    CONSTRAINT fk_tv_vehicle FOREIGN KEY (vehicle_id) REFERENCES travel_vehicles(vehicle_id)
);

CREATE TABLE invoices (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    status VARCHAR(20) NOT NULL,
    discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    service_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
    total_amount DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(20) NULL,
    customer_name VARCHAR(255) NULL,
    customer_phone VARCHAR(20) NULL,
    customer_email VARCHAR(255) NULL,
    booking_id BIGINT NULL UNIQUE,
    CONSTRAINT ck_invoice_amounts CHECK (
        discount_amount >= 0 AND tax_amount >= 0 AND service_fee >= 0 AND total_amount >= 0
    ),
    CONSTRAINT ck_invoice_status CHECK (status IN ('PAID', 'UNPAID')),
    CONSTRAINT ck_invoice_payment_method CHECK (
        payment_method IS NULL OR payment_method IN ('CASH', 'VNPAY', 'MOMO', 'CARD')
    )
);

CREATE TABLE invoice_promotions (
    invoice_id BIGINT NOT NULL,
    promotion_id BIGINT NOT NULL,
    PRIMARY KEY (invoice_id, promotion_id),
    CONSTRAINT fk_ip_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id),
    CONSTRAINT fk_ip_promotion FOREIGN KEY (promotion_id) REFERENCES promotions(promotion_id)
);

CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(255) NOT NULL,
    customer_email VARCHAR(255) NULL,
    customer_phone VARCHAR(20) NULL,
    customer_address VARCHAR(255) NULL,
    customer_date_of_birth DATE NULL,
    account_id BIGINT NULL UNIQUE,
    CONSTRAINT fk_customer_account FOREIGN KEY (account_id) REFERENCES accounts(account_id)
);

-- ============================================================
-- PART 2: BOOKING FLOOR
-- ============================================================

-- A departure is a dated, capacity-limited, priced instance of a tour.
CREATE TABLE tour_departures (
    departure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL,
    departure_start_date TIMESTAMP NOT NULL,
    departure_end_date TIMESTAMP NOT NULL,
    departure_capacity INT NOT NULL,
    departure_booked_slots INT NOT NULL DEFAULT 0,
    departure_price DECIMAL(12,2) NOT NULL,
    departure_meeting_point VARCHAR(255) NULL,
    departure_status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    departure_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_departure_tour FOREIGN KEY (tour_id) REFERENCES tours(tour_id),
    CONSTRAINT ck_departure_capacity CHECK (
        departure_capacity > 0
        AND departure_booked_slots >= 0
        AND departure_booked_slots <= departure_capacity
    ),
    CONSTRAINT ck_departure_dates CHECK (departure_end_date > departure_start_date),
    CONSTRAINT ck_departure_price CHECK (departure_price >= 0),
    CONSTRAINT ck_departure_status CHECK (
        departure_status IN ('DRAFT', 'OPEN', 'FULL', 'CLOSED', 'CANCELLED')
    )
);

CREATE INDEX idx_departure_tour ON tour_departures (tour_id);
CREATE INDEX idx_departure_status_date ON tour_departures (departure_status, departure_start_date);

-- A booking reserves seats on one departure.
CREATE TABLE bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(16) NOT NULL UNIQUE,
    account_id BIGINT NULL,
    departure_id BIGINT NOT NULL,
    booking_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    booking_guest_count INT NOT NULL DEFAULT 1,
    booking_unit_price DECIMAL(12,2) NOT NULL,
    booking_subtotal DECIMAL(12,2) NOT NULL,
    booking_discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    booking_total_amount DECIMAL(12,2) NOT NULL,
    booking_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    booking_note TEXT NULL,
    CONSTRAINT fk_booking_account FOREIGN KEY (account_id) REFERENCES accounts(account_id),
    CONSTRAINT fk_booking_departure FOREIGN KEY (departure_id) REFERENCES tour_departures(departure_id),
    CONSTRAINT ck_booking_guest_count CHECK (booking_guest_count > 0),
    CONSTRAINT ck_booking_amounts CHECK (
        booking_unit_price >= 0
        AND booking_subtotal >= 0
        AND booking_discount_amount >= 0
        AND booking_total_amount >= 0
    ),
    CONSTRAINT ck_booking_status CHECK (
        booking_status IN ('PENDING', 'PAID', 'CONFIRMED', 'COMPLETED', 'CANCELLED')
    )
);

CREATE INDEX idx_booking_departure ON bookings (departure_id);
CREATE INDEX idx_booking_account ON bookings (account_id);
CREATE INDEX idx_booking_status ON bookings (booking_status);

ALTER TABLE invoices
    ADD CONSTRAINT fk_invoice_booking
    FOREIGN KEY (booking_id) REFERENCES bookings(booking_id);

-- Travelers are the people who actually go on the trip.
CREATE TABLE travelers (
    traveler_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    traveler_name VARCHAR(255) NOT NULL,
    traveler_date_of_birth DATE NULL,
    traveler_gender VARCHAR(10) NULL,
    traveler_id_document VARCHAR(64) NULL,
    CONSTRAINT fk_traveler_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id),
    CONSTRAINT ck_traveler_gender CHECK (
        traveler_gender IS NULL OR traveler_gender IN ('MALE', 'FEMALE', 'OTHER')
    )
);

CREATE INDEX idx_traveler_booking ON travelers (booking_id);

-- Payments are money movements. A booking is paid when successful payments reach its total.
CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    payment_amount DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL,
    payment_provider_txn_id VARCHAR(128) NULL,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    payment_paid_at TIMESTAMP NULL,
    payment_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id),
    CONSTRAINT uq_payment_id_booking UNIQUE (payment_id, booking_id),
    CONSTRAINT ck_payment_amount CHECK (payment_amount > 0),
    CONSTRAINT ck_payment_method CHECK (payment_method IN ('CASH', 'VNPAY', 'MOMO', 'CARD')),
    CONSTRAINT ck_payment_status CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED')),
    CONSTRAINT ck_payment_status_paid_at CHECK (
        (payment_status = 'SUCCESS' AND payment_paid_at IS NOT NULL)
        OR (payment_status IN ('PENDING', 'FAILED') AND payment_paid_at IS NULL)
    )
);

CREATE INDEX idx_payment_booking ON payments (booking_id);
CREATE INDEX idx_payment_status ON payments (payment_status);

CREATE UNIQUE INDEX uq_payment_provider_txn
    ON payments (payment_provider_txn_id)
    WHERE payment_provider_txn_id IS NOT NULL;

-- Refunds are issued against a concrete payment.
CREATE TABLE refunds (
    refund_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,
    refund_amount DECIMAL(12,2) NOT NULL,
    refund_reason TEXT NULL,
    refund_status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    refund_requested_at TIMESTAMP NOT NULL DEFAULT NOW(),
    refund_processed_at TIMESTAMP NULL,
    CONSTRAINT fk_refund_payment_booking FOREIGN KEY (payment_id, booking_id)
        REFERENCES payments(payment_id, booking_id),
    CONSTRAINT ck_refund_amount CHECK (refund_amount > 0),
    CONSTRAINT ck_refund_status CHECK (
        refund_status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'DONE')
    )
);

CREATE INDEX idx_refund_booking ON refunds (booking_id);

