CREATE TABLE account_roles (
    account_role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    account_email VARCHAR(255),
    email_verified SMALLINT NOT NULL DEFAULT 0 CHECK (email_verified IN (0, 1)),
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    account_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    account_updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    role_id BIGINT NOT NULL REFERENCES account_roles(account_role_id)
);

CREATE TABLE accommodations (
    accommodation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accommodation_name VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    rating DECIMAL(3,1) CHECK (rating IS NULL OR rating BETWEEN 0 AND 5),
    price_per_night DECIMAL(12,2) CHECK (price_per_night IS NULL OR price_per_night >= 0),
    accommodation_type VARCHAR(20) CHECK (accommodation_type IS NULL OR accommodation_type IN ('HOTEL', 'RESORT', 'HOMESTAY'))
);

CREATE TABLE travel_vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(255) NOT NULL,
    capacity INT NOT NULL CHECK (capacity > 0),
    rental_price_per_day DECIMAL(12,2) NOT NULL CHECK (rental_price_per_day >= 0)
);

CREATE TABLE tour_guides (
    tour_guide_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_guide_name VARCHAR(255) NOT NULL,
    tour_guide_email VARCHAR(255),
    tour_guide_phone VARCHAR(20),
    tour_guide_experience_years INT NOT NULL DEFAULT 0 CHECK (tour_guide_experience_years >= 0)
);

CREATE TABLE tourist_destinations (
    destination_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_name VARCHAR(255) NOT NULL,
    location VARCHAR(255),
    description TEXT,
    entry_fee DECIMAL(12,2) CHECK (entry_fee IS NULL OR entry_fee >= 0)
);

CREATE TABLE promotions (
    promotion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_name VARCHAR(255) NOT NULL,
    discount_percentage DECIMAL(5,2) NOT NULL CHECK (discount_percentage BETWEEN 0 AND 100),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    description TEXT,
    CHECK (end_date >= start_date)
);

CREATE TABLE tours (
    tour_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_name VARCHAR(255) NOT NULL,
    tour_description TEXT,
    tour_duration_days INT,
    tour_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (tour_status IN ('DRAFT', 'OPEN', 'CLOSED', 'CANCELLED')),
    accommodation_id BIGINT REFERENCES accommodations(accommodation_id),
    tour_guide_id BIGINT REFERENCES tour_guides(tour_guide_id),
    promotion_id BIGINT REFERENCES promotions(promotion_id)
);

CREATE TABLE tour_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url VARCHAR(512) NOT NULL,
    tour_id BIGINT NOT NULL REFERENCES tours(tour_id)
);

CREATE TABLE tour_destinations (
    tour_id BIGINT NOT NULL REFERENCES tours(tour_id),
    destination_id BIGINT NOT NULL REFERENCES tourist_destinations(destination_id),
    PRIMARY KEY (tour_id, destination_id)
);

CREATE TABLE tour_vehicles (
    tour_id BIGINT NOT NULL REFERENCES tours(tour_id),
    vehicle_id BIGINT NOT NULL REFERENCES travel_vehicles(vehicle_id),
    PRIMARY KEY (tour_id, vehicle_id)
);

CREATE TABLE tour_departures (
    departure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL REFERENCES tours(tour_id),
    departure_start_date TIMESTAMP NOT NULL,
    departure_end_date TIMESTAMP NOT NULL,
    departure_capacity INT NOT NULL CHECK (departure_capacity > 0),
    departure_booked_slots INT NOT NULL DEFAULT 0 CHECK (departure_booked_slots >= 0 AND departure_booked_slots <= departure_capacity),
    departure_price DECIMAL(12,2) NOT NULL CHECK (departure_price >= 0),
    departure_meeting_point VARCHAR(255),
    departure_status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (departure_status IN ('OPEN', 'FULL', 'CLOSED', 'CANCELLED')),
    departure_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CHECK (departure_end_date > departure_start_date)
);

CREATE TABLE bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(16) NOT NULL UNIQUE,
    account_id BIGINT REFERENCES accounts(account_id),
    departure_id BIGINT NOT NULL REFERENCES tour_departures(departure_id),
    booking_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    booking_guest_count INT NOT NULL DEFAULT 1 CHECK (booking_guest_count > 0),
    booking_unit_price DECIMAL(12,2) NOT NULL CHECK (booking_unit_price >= 0),
    booking_subtotal DECIMAL(12,2) NOT NULL CHECK (booking_subtotal >= 0),
    booking_discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (booking_discount_amount >= 0),
    booking_total_amount DECIMAL(12,2) NOT NULL CHECK (booking_total_amount >= 0),
    booking_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (booking_status IN ('PENDING', 'PAID', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    booking_note TEXT
);

CREATE TABLE travelers (
    traveler_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(booking_id),
    traveler_name VARCHAR(255) NOT NULL,
    traveler_date_of_birth DATE,
    traveler_gender VARCHAR(10) CHECK (traveler_gender IS NULL OR traveler_gender IN ('MALE', 'FEMALE', 'OTHER')),
    traveler_id_document VARCHAR(64)
);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(booking_id),
    payment_amount DECIMAL(12,2) NOT NULL CHECK (payment_amount > 0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('CASH', 'VNPAY', 'MOMO', 'CARD')),
    payment_provider_txn_id VARCHAR(128),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED')),
    payment_paid_at TIMESTAMP,
    payment_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_payment_id_booking UNIQUE (payment_id, booking_id),
    CHECK ((payment_status = 'SUCCESS' AND payment_paid_at IS NOT NULL) OR (payment_status IN ('PENDING', 'FAILED') AND payment_paid_at IS NULL))
);

CREATE UNIQUE INDEX uq_payment_provider_txn ON payments(payment_provider_txn_id) WHERE payment_provider_txn_id IS NOT NULL;

CREATE TABLE refunds (
    refund_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,
    refund_amount DECIMAL(12,2) NOT NULL CHECK (refund_amount > 0),
    refund_reason TEXT,
    refund_status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED' CHECK (refund_status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'DONE')),
    refund_requested_at TIMESTAMP NOT NULL DEFAULT NOW(),
    refund_processed_at TIMESTAMP,
    FOREIGN KEY (payment_id, booking_id) REFERENCES payments(payment_id, booking_id)
);

CREATE TABLE invoices (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PAID', 'UNPAID')),
    discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    service_fee DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (service_fee >= 0),
    total_amount DECIMAL(12,2) NOT NULL CHECK (total_amount >= 0),
    payment_method VARCHAR(20),
    customer_name VARCHAR(255),
    customer_phone VARCHAR(20),
    customer_email VARCHAR(255),
    booking_id BIGINT UNIQUE REFERENCES bookings(booking_id)
);

CREATE TABLE invoice_promotions (
    invoice_id BIGINT NOT NULL REFERENCES invoices(invoice_id),
    promotion_id BIGINT NOT NULL REFERENCES promotions(promotion_id),
    PRIMARY KEY (invoice_id, promotion_id)
);

CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(255) NOT NULL,
    customer_email VARCHAR(255),
    customer_phone VARCHAR(20),
    customer_address VARCHAR(255),
    customer_date_of_birth DATE,
    account_id BIGINT UNIQUE REFERENCES accounts(account_id)
);

CREATE INDEX idx_departure_tour ON tour_departures(tour_id);
CREATE INDEX idx_departure_status_date ON tour_departures(departure_status, departure_start_date);
CREATE INDEX idx_booking_departure ON bookings(departure_id);
CREATE INDEX idx_booking_account_status ON bookings(account_id, booking_status);
CREATE INDEX idx_payment_booking_status ON payments(booking_id, payment_status);
CREATE INDEX idx_refund_payment ON refunds(payment_id);