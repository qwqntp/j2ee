-- C. TRAVELERS - danh sach khach di thuc te (guest manifest)
-- 1 booking N travelers; khong phan loai tre em/nguoi lon
CREATE TABLE IF NOT EXISTS travelers (
    traveler_id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id             BIGINT       NOT NULL,
    traveler_name          VARCHAR(255) NOT NULL,
    traveler_date_of_birth DATE         NULL,
    traveler_gender        VARCHAR(10)  NULL,                       -- MALE / FEMALE / OTHER
    traveler_id_document   VARCHAR(64)  NULL,                       -- so CCCD / ho chieu
    CONSTRAINT fk_traveler_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id),
    CONSTRAINT ck_traveler_gender CHECK (
        traveler_gender IS NULL OR traveler_gender IN ('MALE', 'FEMALE', 'OTHER')
    )
);

CREATE INDEX IF NOT EXISTS idx_traveler_booking ON travelers (booking_id);

-- D. PAYMENTS - cac lan ghi nhan thanh toan (that bai cung giu lai de audit)
-- Booking PAID khi SUM(payment SUCCESS) >= booking_total_amount
CREATE TABLE IF NOT EXISTS payments (
    payment_id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id              BIGINT        NOT NULL,
    payment_amount          DECIMAL(12,2) NOT NULL,
    payment_method          VARCHAR(20)   NOT NULL,                   -- CASH / VNPAY / MOMO / CARD
    payment_provider_txn_id VARCHAR(128)  NULL,                       -- ma giao dich gateway; NULL voi CASH
    payment_status          VARCHAR(20)   NOT NULL DEFAULT 'PENDING', -- PENDING / SUCCESS / FAILED
    payment_paid_at         TIMESTAMP     NULL,
    payment_created_at      TIMESTAMP     NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id),
    CONSTRAINT uq_payment_id_booking UNIQUE (payment_id, booking_id),
    CONSTRAINT ck_payment_amount CHECK (payment_amount > 0),
    CONSTRAINT ck_payment_status_paid_at CHECK (
        (payment_status = 'SUCCESS' AND payment_paid_at IS NOT NULL)
        OR (payment_status IN ('PENDING', 'FAILED') AND payment_paid_at IS NULL)
    ),
    CONSTRAINT ck_payment_method CHECK (payment_method IN ('CASH', 'VNPAY', 'MOMO', 'CARD')),
    CONSTRAINT ck_payment_status CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS idx_payment_booking ON payments (booking_id);
CREATE INDEX IF NOT EXISTS idx_payment_status ON payments (payment_status);

-- E. REFUNDS - hoan tien (partial duoc phep)
CREATE TABLE IF NOT EXISTS refunds (
    refund_id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          BIGINT        NOT NULL,
    booking_id          BIGINT        NOT NULL,                   -- de truy van nhanh
    refund_amount       DECIMAL(12,2) NOT NULL,
    refund_reason       TEXT          NULL,
    refund_status       VARCHAR(20)   NOT NULL DEFAULT 'REQUESTED', -- REQUESTED/APPROVED/REJECTED/DONE
    refund_requested_at TIMESTAMP     NOT NULL DEFAULT NOW(),
    refund_processed_at TIMESTAMP     NULL,
    CONSTRAINT fk_refund_payment_booking FOREIGN KEY (payment_id, booking_id)
        REFERENCES payments(payment_id, booking_id),
    CONSTRAINT ck_refund_amount CHECK (refund_amount > 0),
    CONSTRAINT ck_refund_status CHECK (refund_status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'DONE'))
);

CREATE INDEX IF NOT EXISTS idx_refund_booking ON refunds (booking_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_provider_txn
    ON payments (payment_provider_txn_id)
    WHERE payment_provider_txn_id IS NOT NULL;
