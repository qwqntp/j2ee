-- Baseline for databases that predate Flyway. IF NOT EXISTS keeps this a no-op
-- on the shared database; fresh databases get the full schema.

-- MySQL ON UPDATE NOW() tuong duong trong PG: trigger
CREATE OR REPLACE FUNCTION set_account_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.account_updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_accounts_updated_at ON public.accounts;

CREATE TRIGGER trg_accounts_updated_at
    BEFORE UPDATE ON accounts
    FOR EACH ROW EXECUTE FUNCTION set_account_updated_at();

CREATE TABLE IF NOT EXISTS accommodations (
    accommodation_id   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accommodation_name VARCHAR(255)  NOT NULL,
    location           VARCHAR(255)  NOT NULL,
    rating             DECIMAL(3,1)  NULL,
    price_per_night    DECIMAL(12,2) NULL,
    accommodation_type VARCHAR(20)   NULL,
    CONSTRAINT ck_accommodation_rating CHECK (rating IS NULL OR (rating >= 0 AND rating <= 5)),
    CONSTRAINT ck_accommodation_price CHECK (price_per_night IS NULL OR price_per_night >= 0),
    CONSTRAINT ck_accommodation_type CHECK (
        accommodation_type IS NULL OR accommodation_type IN ('HOTEL', 'RESORT', 'HOMESTAY')
    )
);

CREATE TABLE IF NOT EXISTS travel_vehicles (
    vehicle_id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type         VARCHAR(255)  NOT NULL,
    capacity             INT           NOT NULL,
    rental_price_per_day DECIMAL(12,2) NOT NULL,
    CONSTRAINT ck_vehicle_capacity CHECK (capacity > 0),
    CONSTRAINT ck_vehicle_rental_price CHECK (rental_price_per_day >= 0)
);

CREATE TABLE IF NOT EXISTS tour_guides (
    tour_guide_id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_guide_name             VARCHAR(255) NOT NULL,
    tour_guide_email            VARCHAR(255) NULL,
    tour_guide_phone            VARCHAR(20)  NULL,
    tour_guide_experience_years INT          NOT NULL DEFAULT 0,
    CONSTRAINT ck_guide_experience CHECK (tour_guide_experience_years >= 0)
);

CREATE TABLE IF NOT EXISTS tourist_destinations (
    destination_id   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_name VARCHAR(255)  NOT NULL,
    location         VARCHAR(255)  NULL,
    description      TEXT          NULL,
    entry_fee        DECIMAL(12,2) NULL,
    CONSTRAINT ck_destination_entry_fee CHECK (entry_fee IS NULL OR entry_fee >= 0)
);

CREATE TABLE IF NOT EXISTS promotions (
    promotion_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_name      VARCHAR(255) NOT NULL,
    discount_percentage DECIMAL(5,2) NOT NULL,
    start_date          DATE         NOT NULL,
    end_date            DATE         NOT NULL,
    description      TEXT          NULL,
    CONSTRAINT ck_promotion_discount CHECK (discount_percentage >= 0 AND discount_percentage <= 100),
    CONSTRAINT ck_promotion_dates CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS tours (
    tour_id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_name           VARCHAR(255)  NOT NULL,
    tour_description    TEXT          NULL,                       -- itinerary gan bang '|', chua tach rieng
    tour_price          DECIMAL(12,2) NOT NULL,                   -- sau migration: doc gia tu tour_departures
    tour_status         VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',   -- DRAFT/OPEN/CLOSED/CANCELLED
    tour_start_date     TIMESTAMP     NULL,
    tour_end_date       TIMESTAMP     NULL,
    tour_meeting_point  VARCHAR(255)  NULL,
    tour_remaining_slots INT          NULL,
    accommodation_id    BIGINT        NULL,
    tour_guide_id       BIGINT        NULL,
    promotion_id        BIGINT        NULL,
    CONSTRAINT fk_tour_accommodation FOREIGN KEY (accommodation_id) REFERENCES accommodations(accommodation_id),
    CONSTRAINT fk_tour_guide         FOREIGN KEY (tour_guide_id)   REFERENCES tour_guides(tour_guide_id),
    CONSTRAINT fk_tour_promotion     FOREIGN KEY (promotion_id)    REFERENCES promotions(promotion_id),
    CONSTRAINT ck_tour_price CHECK (tour_price >= 0),
    CONSTRAINT ck_tour_dates CHECK (tour_start_date IS NULL OR tour_end_date IS NULL OR tour_end_date > tour_start_date),
    CONSTRAINT ck_tour_remaining_slots CHECK (tour_remaining_slots IS NULL OR tour_remaining_slots >= 0),
    CONSTRAINT ck_tour_status CHECK (tour_status IN ('DRAFT', 'OPEN', 'CLOSED', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS idx_tour_status ON tours (tour_status);

CREATE TABLE IF NOT EXISTS tour_images (
    image_id  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url VARCHAR(512) NOT NULL,
    tour_id   BIGINT       NOT NULL,
    CONSTRAINT fk_image_tour FOREIGN KEY (tour_id) REFERENCES tours(tour_id)
);

CREATE INDEX IF NOT EXISTS idx_image_tour ON tour_images (tour_id);

CREATE TABLE IF NOT EXISTS tour_destinations (
    tour_id        BIGINT NOT NULL,
    destination_id BIGINT NOT NULL,
    PRIMARY KEY (tour_id, destination_id),
    CONSTRAINT fk_td_tour        FOREIGN KEY (tour_id)        REFERENCES tours(tour_id),
    CONSTRAINT fk_td_destination FOREIGN KEY (destination_id) REFERENCES tourist_destinations(destination_id)
);

CREATE TABLE IF NOT EXISTS tour_vehicles (
    tour_id     BIGINT NOT NULL,
    vehicle_id  BIGINT NOT NULL,
    PRIMARY KEY (tour_id, vehicle_id),
    CONSTRAINT fk_tv_tour    FOREIGN KEY (tour_id)    REFERENCES tours(tour_id),
    CONSTRAINT fk_tv_vehicle FOREIGN KEY (vehicle_id) REFERENCES travel_vehicles(vehicle_id)
);


CREATE TABLE IF NOT EXISTS invoices (
    invoice_id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_created_at TIMESTAMP     NOT NULL DEFAULT NOW(),
    status             VARCHAR(20)   NOT NULL,                   -- PAID / UNPAID (doc cu)
    discount_amount    DECIMAL(12,2) NOT NULL DEFAULT 0,
    tax_amount         DECIMAL(12,2) NOT NULL DEFAULT 0,
    service_fee        DECIMAL(12,2) NOT NULL DEFAULT 0,
    total_amount       DECIMAL(12,2) NOT NULL,
    payment_method     VARCHAR(20)   NULL,
    customer_name      VARCHAR(255)  NULL,                       -- snapshot
    customer_phone     VARCHAR(20)   NULL,
    customer_email     VARCHAR(255)  NULL,
    booking_id         BIGINT        NOT NULL UNIQUE,
    CONSTRAINT ck_invoice_amounts CHECK (
        discount_amount >= 0 AND tax_amount >= 0 AND service_fee >= 0 AND total_amount >= 0
    ),
    CONSTRAINT ck_invoice_status CHECK (status IN ('PAID', 'UNPAID')),
    CONSTRAINT ck_invoice_payment_method CHECK (
        payment_method IS NULL OR payment_method IN ('CASH', 'VNPAY', 'MOMO', 'CARD')
    )
);

CREATE TABLE IF NOT EXISTS invoice_promotions (
    invoice_id   BIGINT NOT NULL,
    promotion_id BIGINT NOT NULL,
    PRIMARY KEY (invoice_id, promotion_id),
    CONSTRAINT fk_ip_invoice   FOREIGN KEY (invoice_id)   REFERENCES invoices(invoice_id),
    CONSTRAINT fk_ip_promotion FOREIGN KEY (promotion_id) REFERENCES promotions(promotion_id)
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name          VARCHAR(255) NOT NULL,
    customer_email         VARCHAR(255) NULL,
    customer_phone         VARCHAR(20)  NULL,
    customer_address       VARCHAR(255) NULL,
    customer_date_of_birth DATE         NULL,
    account_id             BIGINT       NULL UNIQUE,
    CONSTRAINT fk_customer_account FOREIGN KEY (account_id) REFERENCES accounts(account_id)
);

