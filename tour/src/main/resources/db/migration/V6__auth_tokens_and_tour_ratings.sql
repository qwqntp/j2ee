-- Batch 3: one-time auth tokens (password reset / email verification) and tour ratings.

CREATE TABLE IF NOT EXISTS auth_tokens (
    auth_token_id BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT       NOT NULL,
    token_hash    VARCHAR(64)  NOT NULL UNIQUE,
    token_type    VARCHAR(32)  NOT NULL,
    expires_at    TIMESTAMP    NOT NULL,
    used_at       TIMESTAMP    NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_auth_token_account FOREIGN KEY (account_id)
        REFERENCES accounts (account_id) ON DELETE CASCADE,
    CONSTRAINT ck_auth_token_type CHECK (token_type IN ('PASSWORD_RESET', 'EMAIL_VERIFICATION'))
);

CREATE INDEX IF NOT EXISTS idx_auth_token_account
    ON auth_tokens (account_id);
CREATE INDEX IF NOT EXISTS idx_auth_token_lookup
    ON auth_tokens (token_hash, token_type);

CREATE TABLE IF NOT EXISTS tour_ratings (
    rating_id         BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id           BIGINT    NOT NULL,
    account_id        BIGINT    NOT NULL,
    booking_id        BIGINT    NOT NULL UNIQUE,
    rating_value      INT       NOT NULL,
    rating_comment    TEXT      NULL,
    rating_created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_rating_tour FOREIGN KEY (tour_id)
        REFERENCES tours (tour_id) ON DELETE CASCADE,
    CONSTRAINT fk_rating_account FOREIGN KEY (account_id)
        REFERENCES accounts (account_id) ON DELETE CASCADE,
    CONSTRAINT fk_rating_booking FOREIGN KEY (booking_id)
        REFERENCES bookings (booking_id) ON DELETE CASCADE,
    CONSTRAINT ck_rating_value CHECK (rating_value BETWEEN 1 AND 5)
);

CREATE INDEX IF NOT EXISTS idx_rating_tour_created
    ON tour_ratings (tour_id, rating_created_at DESC);
CREATE INDEX IF NOT EXISTS idx_rating_account
    ON tour_ratings (account_id);
